import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const projectRoot = path.resolve(__dirname, '../../');
const extensionDir = path.join(projectRoot, 'project-support/extension/lptff-investment-assistant');

function computeDigest(filePaths) {
  const hash = crypto.createHash('sha256');
  for (const fp of filePaths) {
    if (fs.existsSync(fp)) {
      const content = fs.readFileSync(fp, 'utf8').replace(/\r\n/g, '\n');
      hash.update(content, 'utf8');
    } else {
      console.warn('Digest source file missing:', fp);
    }
  }
  return hash.digest('hex').slice(0, 10);
}

// 1. 扩展核心源码（严格排除自动生成的 build-info.js，消除自引用）
const extFiles = [
  path.join(extensionDir, 'manifest.json'),
  path.join(extensionDir, 'background.js'),
  path.join(extensionDir, 'authorized-content.js'),
  path.join(extensionDir, 'content/web-bridge.js'),
];
const extDigest = computeDigest(extFiles);
const extBuildTag = `cand-3.25.0-${extDigest}`;

// 2. 网页端核心源码（严格排除自动生成的 build-info.ts，消除自引用）
const webFiles = [
  path.join(projectRoot, 'src/utils/authorizedContent.ts'),
  path.join(projectRoot, 'src/views/home/entertainment/component/AuthorizedCollection.vue'),
];
const webDigest = computeDigest(webFiles);
const webBuildTag = `cand-web-${webDigest}`;
const now = new Date().toISOString();

// 3. 写入扩展运行时标识文件 build-info.js
const extBuildInfoFile = path.join(extensionDir, 'build-info.js');
const extBuildInfoContent = `// Auto-generated by project-support/scripts/generate-build-tags.mjs. Do not edit manually.
(function (root) {
  var info = {
    version: "3.25.0",
    buildTag: "${extBuildTag}",
    builtAt: "${now}"
  };
  if (typeof self !== "undefined") {
    self.__LPTFF_EXTENSION_BUILD_INFO__ = info;
  }
  if (typeof window !== "undefined") {
    window.__LPTFF_EXTENSION_BUILD_INFO__ = info;
  }
})(typeof globalThis !== "undefined" ? globalThis : this);
`;
fs.writeFileSync(extBuildInfoFile, extBuildInfoContent, 'utf8');

// 4. 写入前端网页运行时标识文件 src/build-info.ts
const webBuildInfoFile = path.join(projectRoot, 'src/build-info.ts');
const webBuildInfoContent = `// Auto-generated by project-support/scripts/generate-build-tags.mjs. Do not edit manually.
export const WEB_BUILD_TAG = "${webBuildTag}";
export const EXPECTED_EXTENSION_BUILD_TAG = "${extBuildTag}";
export const EXTENSION_VERSION = "3.25.0";
export const BUILT_AT = "${now}";
`;
fs.writeFileSync(webBuildInfoFile, webBuildInfoContent, 'utf8');

console.log('Build tags generated successfully:');
console.log(`  Extension Build Tag: ${extBuildTag} -> ${extBuildInfoFile}`);
console.log(`  Web Build Tag:       ${webBuildTag} -> ${webBuildInfoFile}`);
