import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { computeBuildTags } from './lib/build-tags.mjs';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const projectRoot = path.resolve(__dirname, '..');
const extensionDir = path.join(projectRoot, 'extension');
const {
  extensionVersion,
  extensionBuildTag: extBuildTag,
  webBuildTag,
} = computeBuildTags(projectRoot);
const now = new Date().toISOString();

// 3. 写入扩展运行时标识文件 build-info.js
const extBuildInfoFile = path.join(extensionDir, 'build-info.js');
const extBuildInfoContent = `// Auto-generated by scripts/generate-build-tags.mjs. Do not edit manually.
(function (root) {
  var info = {
    version: "${extensionVersion}",
    buildTag: "${extBuildTag}",
    builtAt: "${now}"
  };
  if (typeof self !== "undefined") {
    self.__LPTFF_EXTENSION_BUILD_INFO__ = info;
  }
  if (typeof window !== "undefined") {
    window.__LPTFF_EXTENSION_BUILD_INFO__ = info;
  }
})(typeof globalThis !== "undefined" ? globalThis : this);
`;
fs.writeFileSync(extBuildInfoFile, extBuildInfoContent, 'utf8');

// 4. 写入前端网页运行时标识文件 src/build-info.ts
const webBuildInfoFile = path.join(projectRoot, 'src/build-info.ts');
const webBuildInfoContent = `// Auto-generated by scripts/generate-build-tags.mjs. Do not edit manually.
export const WEB_BUILD_TAG = "${webBuildTag}";
export const EXPECTED_EXTENSION_BUILD_TAG = "${extBuildTag}";
export const EXTENSION_VERSION = "${extensionVersion}";
export const BUILT_AT = "${now}";
`;
fs.writeFileSync(webBuildInfoFile, webBuildInfoContent, 'utf8');

console.log('Build tags generated successfully:');
console.log(`  Extension Build Tag: ${extBuildTag} -> ${extBuildInfoFile}`);
console.log(`  Web Build Tag:       ${webBuildTag} -> ${webBuildInfoFile}`);
